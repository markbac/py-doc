"""Markdown pages from a Structurizr workspace: one page per level of the C4 model.

The output is sorted and has no times, so generated pages diff cleanly in git.
"""

from __future__ import annotations

import re

import yaml

from .model import (
    Component,
    Container,
    DeploymentNode,
    Element,
    InfrastructureNode,
    Person,
    SoftwareSystem,
    View,
    Workspace,
)

LEVELS = ("context", "containers", "components", "relationships", "deployment", "dynamic", "catalogue", "documentation")
PAGE_NAMES = {
    "context": "01_context.md", "containers": "02_containers.md", "components": "03_components.md",
    "relationships": "04_relationships.md", "deployment": "05_deployment.md", "dynamic": "06_dynamic.md",
    "catalogue": "07_catalogue.md", "documentation": "08_documentation.md",
}  # fmt: skip
TITLES = {
    "context": "System context", "containers": "Containers", "components": "Components", "relationships": "Relationships",
    "deployment": "Deployment", "dynamic": "Dynamic behaviour", "catalogue": "Element catalogue", "documentation": "Documentation",
}  # fmt: skip
# Text in the pages that a project can replace. Fields: {workspace}, {name}, {description}, {count}.
TEMPLATES = {
    "context": "{description}\n\nThe system landscape of {workspace}: the people and systems around it.",
    "containers": "The containers (applications and data stores) of each system in {workspace}.",
    "components": "The components inside each container.",
    "relationships": "Every relationship in {workspace}. Each arrow in a diagram has a row here.",
    "deployment": "Where the containers of {workspace} run.",
    "dynamic": "How the parts of {workspace} work together, step by step.",
    "catalogue": "Every element of {workspace}, with a glossary of the terms used.",
    "system": "{description}",
    "container": "{description}",
}  # fmt: skip


def _cell(text: str) -> str:
    return re.sub(r"\s+", " ", text or "").replace("|", "\\|").strip()


def _table(headers: list[str], rows: list[list[str]]) -> list[str]:
    if not rows:
        return ["_None._", ""]
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return [*lines, ""]


def _tags(element: Element) -> str:
    return ", ".join(
        t for t in element.tags if t not in ("Element", "Person", "Software System", "Container", "Component")
    )


def _by_name(items: list[Element]) -> list[Element]:
    return sorted(items, key=lambda e: (e.name.lower(), e.id))


class _Writer:
    def __init__(
        self,
        ws: Workspace,
        source: str,
        images: dict[str, str],
        templates: dict[str, str],
        systems: list[str] | None,
        sources: dict[str, tuple[str, str]],
    ):
        self.ws, self.source, self.images, self.templates = ws, source, images, {**TEMPLATES, **templates}
        self.sources = sources
        self.systems = {s.lower() for s in systems} if systems else None

    def say(self, key: str, **fields) -> str:
        values = {"workspace": self.ws.name, "description": "", "name": "", "count": "", **fields}
        return self.templates[key].format(**values).strip()

    def wanted(self, system: Element) -> bool:
        return self.systems is None or system.name.lower() in self.systems or system.id.lower() in self.systems

    def page(self, level: str, body: list[str]) -> str:
        meta = {"title": TITLES[level] if level != "context" else self.ws.name, "workspace": self.ws.name}
        if self.ws.properties.get("version"):
            meta["version"] = self.ws.properties["version"]
        head = "---\n" + yaml.safe_dump(meta, sort_keys=False, allow_unicode=True).rstrip() + "\n---\n"
        note = f"<!-- Generated by py-doc from {self.source}. Do not edit: changes are lost when it is generated again. -->\n"
        return head + "\n" + note + "\n" + "\n".join(body).rstrip() + "\n"

    def views(self, kinds: tuple[str, ...], scope: Element | None = None) -> list[str]:
        lines: list[str] = []
        for view in self.ws.views:
            if view.kind not in kinds or (scope is not None and view.scope_id != scope.id):
                continue
            lines += self.figure(view)
        return lines

    def figure(self, view: View) -> list[str]:
        if view.key not in self.images and view.key not in self.sources:
            return []  # nothing to show: a heading with no picture under it would only confuse
        out = [f"## View: {view.heading}", ""]
        if view.description:
            out += [view.description, ""]
        image = self.images.get(view.key)
        if image:
            out += [f"[[CAPTION:Figure]] {view.heading}", f"![{view.heading}]({image})", ""]
        elif view.key in self.sources:
            language, text = self.sources[view.key]
            out += [
                f"Diagram source ({language}) of the view '{view.heading}':",
                "",
                f"```{language}",
                text.rstrip(),
                "```",
                "",
            ]
        return out

    # -- the pages ------------------------------------------------------------------------------

    def context(self) -> str:
        ws = self.ws
        people, systems = ws.of_kind(Person), [s for s in ws.of_kind(SoftwareSystem) if self.wanted(s)]
        body = [f"# {ws.name}", "", self.say("context", description=ws.description), ""]
        body += self.views(("systemLandscape", "systemContext"))
        body += ["## People", ""]
        body += _table(["Name", "Description", "Tags"], [[p.name, p.description, _tags(p)] for p in people])
        body += ["## Software systems", ""]
        body += _table(["Name", "Description", "Tags"], [[s.name, s.description, _tags(s)] for s in systems])
        return self.page("context", body)

    def containers(self) -> str:
        body = ["# Containers", "", self.say("containers"), ""]
        for system in (s for s in self.ws.of_kind(SoftwareSystem) if self.wanted(s) and s.children):
            body += [f"## {system.name}", "", self.say("system", description=system.description, name=system.name), ""]
            rows = [[c.name, c.technology, c.description, "; ".join(f"{k}: {v}" for k, v in c.properties.items())]
                    for c in _by_name(system.children)]  # fmt: skip
            body += _table(["Container", "Technology", "Description", "Properties"], rows)
            body += [line.replace("## View:", "### View:") for line in self.views(("container",), system)]
            body += self.perspectives(system.children)
        return self.page("containers", body)

    def components(self) -> str:
        body = ["# Components", "", self.say("components"), ""]
        for system in (s for s in self.ws.of_kind(SoftwareSystem) if self.wanted(s)):
            for container in (c for c in _by_name(system.children) if c.children):
                body += [f"## {system.name}: {container.name}", ""]
                if container.description:
                    body += [self.say("container", description=container.description, name=container.name), ""]
                rows = [[c.name, c.technology, c.description] for c in _by_name(container.children)]
                body += _table(["Component", "Technology", "Description"], rows)
                body += [line.replace("## View:", "### View:") for line in self.views(("component",), container)]
        return self.page("components", body)

    def relationships(self) -> str:
        ws = self.ws
        rows = sorted(
            [ws.name_of(r.source_id), ws.name_of(r.destination_id), r.description, r.technology]
            for r in ws.relationships
            if r.linked_id is None
        )
        body = ["# Relationships", "", self.say("relationships"), ""]
        body += _table(["Source", "Destination", "Description", "Technology"], rows)
        return self.page("relationships", body)

    def deployment(self) -> str:
        body = ["# Deployment", "", self.say("deployment"), ""]
        environments = sorted({n.environment for n in self.ws.of_kind(DeploymentNode) if n.parent_id is None})
        for environment in environments:
            body += [f"## {environment or 'Default'}", ""]

            def walk(node: Element, depth: int) -> list[str]:
                tech = f" ({node.technology})" if node.technology else ""
                lines = ["  " * depth + f"- {node.name}{tech}"]
                for child in node.children:
                    if isinstance(child, (DeploymentNode, InfrastructureNode)) or child.kind.endswith("Instance"):
                        lines += walk(child, depth + 1)
                return lines

            for node in _by_name(
                [n for n in self.ws.of_kind(DeploymentNode) if n.parent_id is None and n.environment == environment]
            ):
                body += walk(node, 0)
            body += [""]
            body += [line.replace("## View:", "### View:") for line in self.dep_views(environment)]
        return self.page("deployment", body)

    def dep_views(self, environment: str) -> list[str]:
        return [
            line
            for v in self.ws.views
            if v.kind == "deployment" and v.environment == environment
            for line in self.figure(v)
        ]

    def dynamic(self) -> str:
        body = ["# Dynamic behaviour", "", self.say("dynamic"), ""]
        by_id = {r.id: r for r in self.ws.relationships}
        for view in (v for v in self.ws.views if v.kind == "dynamic"):
            body += self.figure(view)
            for step in view.steps:
                rel = by_id.get(step.relationship_id)
                if rel is None:
                    continue
                text = step.description or rel.description
                body.append(f"1. {self.ws.name_of(rel.source_id)} to {self.ws.name_of(rel.destination_id)}: {text}")
            body.append("")
        return self.page("dynamic", body)

    def perspectives(self, elements: list[Element]) -> list[str]:
        rows = [[e.name, p.name, p.description] for e in _by_name(elements) for p in e.perspectives]
        return ["### Perspectives", "", *_table(["Element", "Perspective", "Description"], rows)] if rows else []

    def catalogue(self) -> str:
        ws = self.ws
        body = ["# Element catalogue", "", self.say("catalogue"), ""]
        rows = [
            [e.name, e.kind, e.technology, e.description]
            for e in _by_name([e for e in ws.elements.values() if not e.kind.endswith("Instance")])
        ]
        body += _table(["Name", "Type", "Technology", "Description"], rows)
        body += ["## Glossary", ""]
        terms = sorted(
            {
                (e.name, e.description)
                for e in ws.elements.values()
                if e.description and not e.kind.endswith("Instance")
            },
            key=lambda t: t[0].lower(),
        )
        body += _table(["Term", "Meaning"], [[n, d] for n, d in terms])
        return self.page("catalogue", body)

    def documentation(self) -> str:
        ws = self.ws
        body = ["# Documentation", ""]
        for section in ws.documentation:
            body += [f"## {section.title}", "", section.content.strip(), ""]
        for element in (e for e in _by_name(list(ws.elements.values())) if e.documentation):
            for section in element.documentation:
                body += [f"## {element.name}: {section.title}", "", section.content.strip(), ""]
        if ws.decisions:
            body += ["# Decisions", ""]
            body += [line for d in ws.decisions for line in (f"## {d.title}", "", d.content.strip(), "")]
        return self.page("documentation", body)


def glossary(ws: Workspace) -> dict[str, list[str]]:
    """Element names as canonical terms, for the lint glossary: no wrong spellings are known, so the lists are empty."""
    return {e.name: [] for e in ws.elements.values() if not e.kind.endswith("Instance")}


def generate(
    ws: Workspace,
    source: str,
    *,
    levels: list[str] | None = None,
    systems: list[str] | None = None,
    images: dict[str, str] | None = None,
    templates: dict[str, str] | None = None,
    sources: dict[str, tuple[str, str]] | None = None,
) -> dict[str, str]:
    """File name -> Markdown for the chosen ``levels`` (all by default). Empty levels are left out.

    ``images`` maps a view key to a picture path, and ``sources`` maps one to ``(language, text)`` of its diagram source.
    """
    chosen = list(levels) if levels else list(LEVELS)
    unknown = [level for level in chosen if level not in LEVELS]
    if unknown:
        raise ValueError(f"Unknown level '{unknown[0]}'. Levels: {', '.join(LEVELS)}")
    writer = _Writer(ws, source, images or {}, templates or {}, systems, sources or {})
    kinds = {e.__class__ for e in ws.elements.values()}
    has = {
        "components": Component in kinds, "containers": Container in kinds, "deployment": DeploymentNode in kinds,
        "dynamic": any(v.kind == "dynamic" for v in ws.views),
        "documentation": bool(ws.documentation or ws.decisions or any(e.documentation for e in ws.elements.values())),
    }  # fmt: skip
    pages = {}
    for level in LEVELS:
        if level in chosen and has.get(level, True):
            pages[PAGE_NAMES[level]] = getattr(writer, level)()
    return pages
